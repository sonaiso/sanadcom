#!/usr/bin/env python3
"""Explanation cards for Mashru's hundred governors, mirrored from its sealed Lean deposits (no new grammar here).

For every row of the owner's table (SLGE/AwamilTable.lean: governor, class 1..13, implied?) the card carries:
  - the class name (Jisr/Awamil.lean `sinfIsm`) and its equations (`muadalat`: alternatives of (role, case),
    roles by `dawrIsm`, cases by `Irab.ramz`: رفع 1، نصب 0، جرّ 2، جزم 3) and the equality links (`rawabit`);
  - the governor's part of speech (اسم/فعل/حرف) exactly as Jisr/AqsamAwamil.lean derives it: first from the
    owner's families in SLGE/Wad.lean (`qismOf`: name match after `tajrid`, with the Qatr al-Nada line of the
    family), else from the transmitted line in a sealed book (`naql`: Mughni, Jana Dani, Alfiyya, Sibawayhi, with
    its line number, the quotation as deposited, and whether the part of speech is inferred, `istidlal`);
    two parts of speech for the shared forms (خلا، عدا، حاشا); none for what Mashru left without a ruling.

This module is a Python mirror of those Lean definitions; the Lean file hashes are recorded in every output, and
`--check` compares the mirror with a table generated by Lean itself (`#eval`), when one is supplied.
The facts Mashru proves about its own deposit (`mujam_98`, `mujam_45`, `naql_fi_jadwal`, `awamil_table`) are the
oracle for this mirror's tests. Matching the hundred to al-Jurjani's own count is outside Mashru's scope by the
owner's decision (his book is not deposited), so no samāʿī/qiyāsī/maʿnawī axis is claimed here.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

CASE_NAME = {1: "رفع", 0: "نصب", 2: "جرّ", 3: "جزم"}  # Irab.ramz
ROLE_NAME = {
    0: "الاسم/المفعول الأوّل",
    1: "الخبر/المفعول الثاني",
    2: "الفعل المضارع",
    6: "المجرور",
    9: "المعطوف عليه",
    10: "المعطوف",
    11: "فعل الشرط",
    12: "جواب الشرط",
    13: "المنادى",
}  # dawrIsm
CLASS_NAME = {
    1: "كان وأخواتها",
    2: "إنّ وأخواتها",
    3: "ظنّ وأخواتها",
    4: "نواصب المضارع",
    5: "جوازم المضارع",
    6: "كاد وأخواتها",
    7: "حروف الجرّ",
    8: "حروف العطف",
    9: "لام التعليل",
    10: "أدوات الشرط الجازمة",
    11: "أدوات الشرط غير الجازمة",
    12: "أدوات الاستفهام",
    13: "أدوات النداء",
}  # sinfIsm
EQUATIONS = {
    1: [[(0, 1), (1, 0)]],
    2: [[(0, 0), (1, 1)]],
    3: [[(0, 0), (1, 0)]],
    4: [[(2, 0)]],
    5: [[(2, 3)]],
    6: [[(0, 1), (2, 1)]],
    7: [[(6, 2)]],
    9: [[(6, 2)], [(2, 0)]],
    10: [[(11, 3), (12, 3)]],
    13: [[(13, 0)], [(13, 1)]],
}  # muadalat; other classes: [[]] (no case imposed)
LINKS = {8: [(9, 10)]}  # rawabit: the follower takes its head's case
FAMILY_OF_CLASS = {
    1: "kanaF",
    2: "innaF",
    3: "zannaF",
    4: "nasbF",
    5: "jazm1F",
    7: "jarrF",
}  # AqsamAwamil.aila
KIND_NAME = {"ism": "اسم", "fil": "فعل", "harf": "حرف"}
BOOK_NAME = {
    "mughni": "مغني اللبيب",
    "janadani": "الجنى الداني",
    "alfiyya": "الألفية",
    "sibawayhi": "الكتاب",
}

TABLE_ROW = re.compile(r'^\s*\("([^"]+)",\s*(\d+),\s*(true|false)\),?\s*$')
FAM = re.compile(r"fam\s*\[([^\]]*)\]\s*\((?:some\s*\.(\w+)|none)\)\s*(\d+)", re.DOTALL)
FAM_DEF = re.compile(
    r"def\s+(\w+F)\s*:\s*List\s+Amil\s*:=(.*?)(?=\n/--|\ndef\s|\ntheorem|\Z)", re.DOTALL
)
NAQL = re.compile(
    r'⟨"([^"]+)",\s*(\d+),\s*\.(\w+),\s*\.(\w+),\s*(\d+),\s*"((?:[^"\\]|\\.)*)",\s*(true|false)⟩'
)
STRIP = set("َُِّْ ًٌٍ ")


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def tajrid(s: str) -> str:
    """Mashru's `tajrid`: drop what stands between parentheses, the marks, the shadda, the tanwin and spaces."""
    out, inside = [], False
    for c in s:
        if c == "(":
            inside = True
        elif c == ")":
            inside = False
        elif inside or c in STRIP:
            continue
        else:
            out.append(c)
    return "".join(out)


def load_table(mashru: Path) -> list[tuple[str, int, bool]]:
    rows = []
    for line in (
        (mashru / "SLGE" / "AwamilTable.lean").read_text(encoding="utf-8").split("\n")
    ):
        m = TABLE_ROW.match(line)
        if m:
            rows.append((m.group(1), int(m.group(2)), m.group(3) == "true"))
    return rows


def load_families(mashru: Path) -> dict[str, list[dict]]:
    """Owner families of SLGE/Wad.lean: name -> [{name, kind, line}] per family definition (kanaF, ...)."""
    text = (mashru / "SLGE" / "Wad.lean").read_text(encoding="utf-8")
    families: dict[str, list[dict]] = {}
    for m in FAM_DEF.finditer(text):
        fname, body = m.group(1), m.group(2)
        entries = []
        for fm in FAM.finditer(body):
            names = re.findall(r'"([^"]*)"', fm.group(1))
            entries += [
                {"name": n, "kind": fm.group(2), "line": int(fm.group(3))}
                for n in names
            ]
        if entries:
            families[fname] = entries
    return families


def load_naql(mashru: Path) -> list[dict]:
    text = (mashru / "Jisr" / "AqsamAwamil.lean").read_text(encoding="utf-8")
    body = text.split("def naql : List Naql := [", 1)[1].split("\n]", 1)[0]
    return [
        {
            "amil": a,
            "sinf": int(s),
            "qism": q,
            "book": b,
            "line": int(ln),
            "quote": qt,
            "inferred": inf == "true",
        }
        for a, s, q, b, ln, qt, inf in NAQL.findall(body)
    ]


def qism_of(name: str, sinf: int, families: dict) -> dict | None:
    fam = FAMILY_OF_CLASS.get(sinf)
    if not fam:
        return None
    for e in families.get(fam, []):
        if tajrid(e["name"]) == tajrid(name):
            return (
                {
                    "kind": e["kind"],
                    "source": "qatr-family",
                    "family": fam,
                    "line": e["line"],
                }
                if e["kind"]
                else None
            )
    return None


def cards(mashru: Path) -> dict:
    table, families, naql = load_table(mashru), load_families(mashru), load_naql(mashru)
    out = []
    for name, sinf, implied in table:
        kinds: list[dict] = []
        fam_kind = qism_of(name, sinf, families)
        if fam_kind:
            kinds = [fam_kind]
        else:
            kinds = [
                {
                    "kind": n["qism"],
                    "source": n["book"],
                    "line": n["line"],
                    "quote": n["quote"],
                    "inferred": n["inferred"],
                }
                for n in naql
                if n["amil"] == name and n["sinf"] == sinf
            ]
        eqs = [
            [
                {
                    "role": r,
                    "role_name": ROLE_NAME.get(r, "؟"),
                    "case": c,
                    "case_name": CASE_NAME[c],
                }
                for r, c in alt
            ]
            for alt in EQUATIONS.get(sinf, [[]])
        ]
        out.append(
            {
                "governor": name,
                "class": sinf,
                "class_name": CLASS_NAME.get(sinf, "؟"),
                "implied": implied,
                "kinds": kinds,
                "equations": eqs,
                "links": LINKS.get(sinf, []),
            }
        )
    return {
        "schema": "sanadcom.mashru-governor-cards.v1",
        "sources": {
            f: sha(mashru / f)
            for f in (
                "SLGE/AwamilTable.lean",
                "SLGE/Wad.lean",
                "Jisr/AqsamAwamil.lean",
                "Jisr/Awamil.lean",
            )
        },
        "cards": out,
        "counts": {
            "governors": len(out),
            "with_kind": sum(1 for c in out if c["kinds"]),
            "from_families": sum(
                1
                for c in out
                if c["kinds"] and c["kinds"][0]["source"] == "qatr-family"
            ),
            "two_kinds": sum(1 for c in out if len(c["kinds"]) == 2),
            "without_ruling": [c["governor"] for c in out if not c["kinds"]],
        },
    }


def explain(card: dict) -> str:
    """One Arabic sentence generated from the card's data only (no hand text per governor)."""
    kinds = card["kinds"]
    if not kinds:
        kind = "قسمُه بلا حكم في Mashru"
    else:
        parts = []
        for k in kinds:
            src = (
                f"قطر الندى (عائلة {k['family']}، السطر {k['line']})"
                if k["source"] == "qatr-family"
                else f"{BOOK_NAME.get(k['source'], k['source'])} السطر {k['line']}{' بالاستدلال' if k.get('inferred') else ''}"
            )
            parts.append(f"{KIND_NAME.get(k['kind'], k['kind'])} ({src})")
        kind = " أو ".join(parts)
    verb = {1: "ترفع", 0: "تنصب", 2: "تجرّ", 3: "تجزم"}
    alts = [
        " و".join(f"{verb[e['case']]} {e['role_name']}" for e in alt)
        for alt in card["equations"]
        if alt
    ]
    effect = " أو ".join(alts) if alts else "لا فرضَ إعرابيٍّ لها في الجدول"
    links = (
        "; "
        + "، ".join(
            f"{ROLE_NAME[b]} يأخذ حالة {ROLE_NAME[a]}" for a, b in card["links"]
        )
        if card["links"]
        else ""
    )
    return f"«{card['governor']}»: {kind}؛ من {card['class_name']}: {effect}{links}."


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--mashru-src", type=Path, required=True)
    ap.add_argument("--out", type=Path, default=None)
    ap.add_argument(
        "--check",
        type=Path,
        default=None,
        help="a TSV generated by Lean (#eval): governor, class, kinds",
    )
    ap.add_argument(
        "--explain",
        nargs="*",
        default=None,
        help="print the sentence for these governors",
    )
    args = ap.parse_args(argv[1:])
    data = cards(args.mashru_src)
    if args.check:
        lean = {}
        for line in args.check.read_text(encoding="utf-8").split("\n"):
            if line.strip():
                parts = line.split("\t")
                if len(parts) != 3:
                    print(f"LEAN_TABLE_MALFORMED: {line[:60]!r}")
                    return 1
                g, s, k = parts
                lean[(g, int(s))] = k
        mine = {
            (c["governor"], c["class"]): ",".join(k["kind"] for k in c["kinds"])
            or "none"
            for c in data["cards"]
        }
        if lean != mine:
            diff = [k for k in set(lean) | set(mine) if lean.get(k) != mine.get(k)]
            print(f"MIRROR_DIFFERS_FROM_LEAN: {len(diff)} rows, e.g. {diff[:5]}")
            return 1
        print(f"mirror matches the Lean table: {len(mine)} rows")
    if args.out:
        args.out.write_text(
            json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8"
        )
    c = data["counts"]
    print(
        f"governors {c['governors']}  with kind {c['with_kind']}  from families {c['from_families']}  two kinds {c['two_kinds']}  without ruling {c['without_ruling']}"
    )
    for g in args.explain or []:
        for card in data["cards"]:
            if card["governor"] == g:
                print(" ", explain(card))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
